#!/usr/bin/env bash
# =============================================================================
# i18n.sh — каркас интернационализации CLI-установщика.
#
# Модель gettext: КЛЮЧ перевода = сама исходная русская строка. Перевод берётся
# из lang/<код>.lng; если файла/ключа нет — показываем русский оригинал. Поэтому
# строки можно оборачивать t() ПОСТЕПЕННО: непереведённое просто остаётся русским,
# ничего не ломается. Русский — исходный язык, отдельного ru.lng не требуется.
#
# Использование:
#   ui_box_line "$(t "Панели-расширения ISPConfig")"
#   ui_confirm  "$(t "Ставить все панели-расширения ISPConfig (рекомендуется)?")" y
#
# Язык выбирается (по убыванию приоритета): флаг --lang <код> → UI_LANG в setup.conf
# → переменная окружения UI_LANG → умолчание ru. Доступные коды = имена файлов
# lang/*.lng (+ всегда ru). Добавить язык = положить lang/<код>.lng со строками
# _I18N["<русский оригинал>"]="<перевод>".
# =============================================================================

declare -gA _I18N=()          # ["исходная русская строка"]="translation"
UI_LANG="${UI_LANG:-ru}"      # текущий язык интерфейса

# Каталог языковых файлов (LANG_DIR можно переопределить; по умолчанию рядом со скриптом).
: "${LANG_DIR:=${SCRIPT_DIR:-.}/lang}"

# i18n_load [код] — загрузить переводы для языка. Идемпотентно (очищает и грузит заново).
# ru (или пустой файл) — оставляем оригиналы. Отсутствие файла НЕ ошибка (тихий фолбэк).
i18n_load() {
	local lang="${1:-$UI_LANG}"
	_I18N=()
	UI_LANG="$lang"
	[[ "$lang" == "ru" ]] && return 0          # русский — исходный, файл не нужен
	local f="$LANG_DIR/${lang}.lng"
	[[ -r "$f" ]] || return 0                  # нет перевода — молча остаёмся на русском
	# shellcheck disable=SC1090
	source "$f" 2>/dev/null || true
}

# i18n_langs — список доступных кодов языков (ru + найденные lang/*.lng), по одному в строке.
i18n_langs() {
	echo ru
	local f
	for f in "$LANG_DIR"/*.lng; do
		[[ -e "$f" ]] || continue
		basename "$f" .lng
	done
}

# t "русская строка" — вернуть перевод для UI_LANG или сам оригинал (без перевода).
# НЕ добавляет перевод строки: пригодно для подстановки в кавычках.
t() {
	local s="$1"
	if [[ "$UI_LANG" != "ru" && -n "${_I18N[$s]:-}" ]]; then
		printf '%s' "${_I18N[$s]}"
	else
		printf '%s' "$s"
	fi
}
